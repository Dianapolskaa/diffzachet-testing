#pragma once
#include <string>
#include <vector>

namespace mylib {

// Подсчёт количества слов в строке. Слова разделяются любыми пробельными символами.
// Пустая строка или строка, состоящая только из пробелов/табуляций, возвращает 0.
int countWords(const std::string& s);

// Подсчёт количества вхождений заданного символа в строку (регистрозависимо).
// Если символ не найден или строка пуста, возвращает 0.
int countCharOccurrences(const std::string& s, char c);

// Возвращает самую частую букву (a-z, A-Z) в строке.
// Если в строке нет ни одной буквы, возвращает символ '\0'.
// При равенстве частот возвращает ту, которая встретилась первой.
char mostFrequentLetter(const std::string& s);

// Возвращает длину самой длинной строки в массиве.
// Если массив пуст или содержит только пустые строки, возвращает 0.
size_t longestStringLength(const std::vector<std::string>& arr);

} // namespace mylib