#pragma once
#include <string>
#include <stdexcept>

namespace mylib {

// Вычисляет значение арифметического выражения из строки.
// Поддерживает: +, -, *, /, скобки (), унарный минус и плюс, десятичные дроби.
//
// Обработка ошибок (бросает std::invalid_argument):
// - Пустая строка или строка только из пробелов.
// - Некорректные символы (мусор в выражении, например "2 + a").
// - Несбалансированные скобки (например, "(2 + 2" или "2 + 2)").
// - Деление на ноль.
// - Лишние символы после корректного выражения (например, "2 + 2 abc").
double evaluateExpression(const std::string& expr);

} // namespace mylib